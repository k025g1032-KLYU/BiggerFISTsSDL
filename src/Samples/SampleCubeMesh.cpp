#include "Samples/SampleCubeMesh.h"

MeshData MakeSampleCubeMesh(const std::filesystem::path& texturePath) {
    MeshData mesh;
    mesh.vertices = {
        // Front (-Z).
        { { -0.5f, 0.5f, -0.5f }, { 0.0f, 0.0f } },
        { { 0.5f, 0.5f, -0.5f }, { 1.0f, 0.0f } },
        { { 0.5f, -0.5f, -0.5f }, { 1.0f, 1.0f } },
        { { -0.5f, -0.5f, -0.5f }, { 0.0f, 1.0f } },
        // Back (+Z).
        { { 0.5f, 0.5f, 0.5f }, { 0.0f, 0.0f } },
        { { -0.5f, 0.5f, 0.5f }, { 1.0f, 0.0f } },
        { { -0.5f, -0.5f, 0.5f }, { 1.0f, 1.0f } },
        { { 0.5f, -0.5f, 0.5f }, { 0.0f, 1.0f } },
        // Left (-X).
        { { -0.5f, 0.5f, 0.5f }, { 0.0f, 0.0f } },
        { { -0.5f, 0.5f, -0.5f }, { 1.0f, 0.0f } },
        { { -0.5f, -0.5f, -0.5f }, { 1.0f, 1.0f } },
        { { -0.5f, -0.5f, 0.5f }, { 0.0f, 1.0f } },
        // Right (+X).
        { { 0.5f, 0.5f, -0.5f }, { 0.0f, 0.0f } },
        { { 0.5f, 0.5f, 0.5f }, { 1.0f, 0.0f } },
        { { 0.5f, -0.5f, 0.5f }, { 1.0f, 1.0f } },
        { { 0.5f, -0.5f, -0.5f }, { 0.0f, 1.0f } },
        // Top (+Y).
        { { -0.5f, 0.5f, 0.5f }, { 0.0f, 0.0f } },
        { { 0.5f, 0.5f, 0.5f }, { 1.0f, 0.0f } },
        { { 0.5f, 0.5f, -0.5f }, { 1.0f, 1.0f } },
        { { -0.5f, 0.5f, -0.5f }, { 0.0f, 1.0f } },
        // Bottom (-Y).
        { { -0.5f, -0.5f, -0.5f }, { 0.0f, 0.0f } },
        { { 0.5f, -0.5f, -0.5f }, { 1.0f, 0.0f } },
        { { 0.5f, -0.5f, 0.5f }, { 1.0f, 1.0f } },
        { { -0.5f, -0.5f, 0.5f }, { 0.0f, 1.0f } }
    };
    mesh.indices = {
        0, 1, 2, 0, 2, 3,
        4, 5, 6, 4, 6, 7,
        8, 9, 10, 8, 10, 11,
        12, 13, 14, 12, 14, 15,
        16, 17, 18, 16, 18, 19,
        20, 21, 22, 20, 22, 23
    };
    mesh.texturePath = texturePath;
    return mesh;
}
